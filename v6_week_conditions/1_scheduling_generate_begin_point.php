// Функция для сбора массива из чанков
// Чанки должны быть получены из array_chunks($array, $n)
function array_from_chunks($array){
    $mergedArray = [];
    foreach($array AS $chunk){
        $mergedArray = array_merge($mergedArray, $chunk);
    }
    return $mergedArray;
}